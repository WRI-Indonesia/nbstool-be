"""Generate Rust constants from the original's long text tables, so they are copied, not retyped.

    venv/Scripts/python.exe -I rust/geo/tools/gen_consts.py

Writes rust/geo/src/generated.rs. Run again whenever the Python tables change. Build-time only:
the Rust program never runs Python.
"""
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[2]
sys.path.insert(0, str(REPO / "application" / "utils" / "geos" / "v3"))

import wrb_descriptions  # noqa: E402


def s(v: str) -> str:
    return json.dumps(v, ensure_ascii=False)  # a JSON string is a valid Rust string literal here


out = ["//! GENERATED by tools/gen_consts.py from the Python sources. Do not edit by hand.", ""]
out.append("/// `wrb_descriptions.WRB_DESCRIPTIONS`, in dict order.")
items = list(wrb_descriptions.WRB_DESCRIPTIONS.items())
out.append(f"pub const WRB_DESCRIPTIONS: [(&str, &str); {len(items)}] = [")
out += [f"    ({s(k)}, {s(v)})," for k, v in items]
out.append("];")
out.append(f"pub const WRB_DESCRIPTION_FALLBACK: &str = {s(wrb_descriptions.WRB_DESCRIPTION_FALLBACK)};")
(HERE.parent / "src" / "generated.rs").write_text("\n".join(out) + "\n", encoding="utf-8")
print("wrote src/generated.rs")
